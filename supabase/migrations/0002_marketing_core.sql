create extension if not exists pgcrypto;

create table if not exists public.campaign_types (
  name text primary key,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

insert into public.campaign_types (name, position) values
  ('Tips', 0), ('Brand Spotlight', 1), ('Sales Ads', 2)
on conflict (name) do nothing;

create table if not exists public.campaigns (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  objective text not null default '',
  campaign_type text not null default 'Tips' references public.campaign_types(name),
  stage text not null default 'new' check (stage in ('new', 'in_progress', 'done')),
  start_date date,
  end_date date,
  owner_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  title text not null default '',
  caption text not null default '',
  campaign_id uuid references public.campaigns(id) on delete set null,
  channels text[] not null default '{}',
  whatsapp_recipient_type text,
  whatsapp_recipient_id text,
  whatsapp_recipient_name text,
  status text not null default 'draft' check (status in ('draft', 'awaiting_approval', 'scheduled', 'published', 'failed')),
  publish_at timestamptz,
  published_at timestamptz,
  media jsonb not null default '[]'::jsonb,
  provider_ids jsonb not null default '{}'::jsonb,
  last_error text,
  clicks integer,
  reach integer,
  impressions integer,
  views integer,
  likes integer,
  comments integer,
  shares integer,
  reactions integer,
  engagements integer,
  saves integer,
  metrics_refreshed_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists campaigns_updated_at_idx on public.campaigns (updated_at desc);
create index if not exists posts_campaign_id_idx on public.posts (campaign_id);
create index if not exists posts_updated_at_idx on public.posts (updated_at desc);

create or replace function public.set_updated_at() returns trigger
language plpgsql security invoker set search_path = public as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists campaigns_set_updated_at on public.campaigns;
create trigger campaigns_set_updated_at before update on public.campaigns
for each row execute function public.set_updated_at();
drop trigger if exists posts_set_updated_at on public.posts;
create trigger posts_set_updated_at before update on public.posts
for each row execute function public.set_updated_at();

alter table public.campaign_types enable row level security;
alter table public.campaigns enable row level security;
alter table public.posts enable row level security;
alter table public.audit_log enable row level security;

