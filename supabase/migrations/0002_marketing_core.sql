create policy "active users manage campaign types" on public.campaign_types for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
create policy "active users read campaigns" on public.campaigns for select to authenticated using (public.is_active_user());
create policy "active users manage campaigns" on public.campaigns for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
create policy "active users read posts" on public.posts for select to authenticated using (public.is_active_user());
create policy "active users manage posts" on public.posts for all to authenticated using (public.is_active_user()) with check (public.is_active_user());
create policy "active users read audit log" on public.audit_log for select to authenticated using (public.is_active_user());
create policy "active users write audit log" on public.audit_log for insert to authenticated with check (public.is_active_user());
