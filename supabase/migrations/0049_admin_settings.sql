-- Marketing has one company connection per provider. Preserve every historical
-- row, but nominate the strongest/recent connection as the shared workspace row.
alter table public.provider_connections
  add column if not exists is_workspace_connection boolean not null default false;

with ranked_connections as (
  select id, row_number() over (
    partition by provider
    order by
      case status when 'connected' then 0 when 'warning' then 1 else 2 end,
      last_success_at desc nulls last,
      updated_at desc,
      id
  ) as connection_rank
  from public.provider_connections
)
update public.provider_connections connection
set is_workspace_connection = (ranked.connection_rank = 1)
from ranked_connections ranked
where ranked.id = connection.id;

create unique index if not exists provider_connections_one_workspace_provider_idx
  on public.provider_connections (provider)
  where is_workspace_connection;

drop policy if exists "users read own provider connections" on public.provider_connections;
drop policy if exists "users manage own provider connections" on public.provider_connections;
revoke all on public.provider_connections from authenticated;

create or replace function public.can_access_workspace(workspace_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_active_user() and (
    public.has_role('administrator') or
    (workspace_name = 'sales_desk' and (
      public.has_role('sales') or public.has_role('sales_manager') or public.has_role('management')
    )) or
    (workspace_name = 'returns_claims' and (public.has_role('returns') or public.has_role('management'))) or
    (workspace_name = 'marketing' and (public.has_role('marketing') or public.has_role('management'))) or
    (workspace_name = 'stock_control' and (public.has_role('stock') or public.has_role('management'))) or
    (workspace_name = 'fleet_management' and public.has_role('fleet')) or
    (workspace_name = 'ecommerce' and public.has_role('ecommerce')) or
    (workspace_name = 'reporting' and (public.has_role('reporting') or public.has_role('management') or public.has_role('report_builder')))
  );
$$;

